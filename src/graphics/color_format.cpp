const char* NvColorFormatToString(uint64_t format) {
  size_t first = 0;
  size_t last = format_count;

  while (first < last) {
    size_t middle = first + (last - first) / 2;

    if (formats[middle].format < format) {
      first = middle + 1;
    }
    else {
      last = middle;
    }
  }

  if (first < format_count && formats[first].format == format) {
    return formats[first].name;
  }

  return "custom";
}

uint64_t NvColorFormatFromString(const char* name) {
  if (name == nullptr) {
    return 0;
  }

  for (const auto& entry : formats) {
    if (Equal(entry.name, name)) {
      return entry.format;
    }
  }

  return 0;
}
