#include <stddef.h>
#include <stdint.h>

using CUresult = uint32_t;

// Each entry point hands its argument registers to the driver untouched, so
// all of them are declared with the full register set.
using CudaDriverFunction = CUresult (*)(uint64_t, uint64_t, uint64_t,
  uint64_t, uint64_t, uint64_t, uint64_t, uint64_t);

struct CudaDriverState {
  uint8_t reserved[0x100];
  uint32_t state;
};

struct CudaErrorEntry {
  CUresult code;
  const char* pName;
};

struct CudaApiTable {
  CudaDriverFunction functions[781];
};

[[gnu::visibility("hidden")]] extern CudaDriverState* g_pCudaDriverState;
[[gnu::visibility("hidden")]] extern CudaApiTable g_CudaApiTable;

[[gnu::visibility("hidden")]] const CudaErrorEntry* FindCudaError(
  CUresult result);
[[gnu::visibility("hidden")]] void CudaLog(const char* pCategory, int level,
  const char* pFormat, CUresult result, const char* pErrorName);

namespace {

constexpr uint32_t DriverStateDeinitialized = 0x321cba00;
constexpr CUresult CUDA_ERROR_DEINITIALIZED = 4;
constexpr CUresult CUDA_ERROR_NOT_READY = 600;

// Success, not initialized and deinitialized are expected results.
constexpr uint32_t QuietResults = 0x19;

template<size_t Slot>
[[gnu::always_inline]] inline CUresult CallDriver(const char* pFormat,
  uint64_t a0, uint64_t a1, uint64_t a2, uint64_t a3, uint64_t a4,
  uint64_t a5, uint64_t a6, uint64_t a7) {
  if (g_pCudaDriverState->state == DriverStateDeinitialized) {
    return CUDA_ERROR_DEINITIALIZED;
  }

  const CUresult result =
    g_CudaApiTable.functions[Slot](a0, a1, a2, a3, a4, a5, a6, a7);
  if (result <= 4 && ((1u << result) & QuietResults) != 0) {
    return result;
  }

  if (result == CUDA_ERROR_NOT_READY) {
    return result;
  }

  const CudaErrorEntry* pError = FindCudaError(result);
  CudaLog("CUDA", 0, pFormat, result,
    pError != nullptr ? pError->pName : "UNRECOGNIZED_ERROR");
  return result;
}

}

#define CUDA_ENTRY_POINT(name, slot) \
  CUresult name(uint64_t a0, uint64_t a1, uint64_t a2, uint64_t a3, \
    uint64_t a4, uint64_t a5, uint64_t a6, uint64_t a7) { \
    return CallDriver<slot>("Returning %d (%s) from " #name, a0, a1, a2, \
      a3, a4, a5, a6, a7); \
  }

