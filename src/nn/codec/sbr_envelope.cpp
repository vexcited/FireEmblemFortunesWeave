static void equalizeFiltBufferExp(FIXP_DBL *filtBuffer, SCHAR *filtBuffer_e,
                                  FIXP_DBL *nrgGain, SCHAR *nrgGain_e,
                                  int subbands) {
  int band;
  int diff;
  for (band = 0; band < subbands; band++) {
    diff = (int)(nrgGain_e[band] - filtBuffer_e[band]);
    if (diff > 0) {
      filtBuffer[band] >>= diff;
      filtBuffer_e[band] += diff;
    }
    else if (diff < 0) {
      int reserve = CntLeadingZeros(fixp_abs(filtBuffer[band])) - 1;
      if ((-diff) <= reserve) {
        filtBuffer[band] <<= (-diff);
        filtBuffer_e[band] += diff;
      }
      else {
        filtBuffer[band] <<= reserve;
        filtBuffer_e[band] -= reserve;
        diff = fixMin(-(reserve + diff), 32 - 1);
        nrgGain[band] >>= diff;
        nrgGain_e[band] += diff;
      }
    }
  }
}

void rescaleSubbandSamples(FIXP_DBL **re, FIXP_DBL **im, int lowSubband,
                           int highSubband, int start_pos, int next_pos,
                           int shift) {
  int width = highSubband - lowSubband;
  if ((width > 0) && (shift != 0)) {
    if (im != nullptr) {
      for (int l = start_pos; l < next_pos; l++) {
        scaleValues(&re[l][lowSubband], width, shift);
        scaleValues(&im[l][lowSubband], width, shift);
      }
    }
    else {
      for (int l = start_pos; l < next_pos; l++) {
        scaleValues(&re[l][lowSubband], width, shift);
      }
    }
  }
}

FIXP_DBL maxSubbandSample(FIXP_DBL **re, FIXP_DBL **im, int lowSubband,
                          int highSubband, int start_pos, int next_pos) {
  FIXP_DBL maxVal = fixed_runtime_dbl(0.0f);
  unsigned int width = highSubband - lowSubband;
  if (width > 0) {
    if (im != nullptr) {
      for (int l = start_pos; l < next_pos; l++) {
        int k = width;
        FIXP_DBL *reTmp = &re[l][lowSubband];
        FIXP_DBL *imTmp = &im[l][lowSubband];
        do {
          FIXP_DBL tmp1 = *(reTmp++);
          FIXP_DBL tmp2 = *(imTmp++);
          maxVal |= (FIXP_DBL)((LONG)(tmp1) ^ ((LONG)tmp1 >> (32 - 1)));
          maxVal |= (FIXP_DBL)((LONG)(tmp2) ^ ((LONG)tmp2 >> (32 - 1)));
        } while (--k != 0);
      }
    }
    else {
      for (int l = start_pos; l < next_pos; l++) {
        int k = width;
        FIXP_DBL *reTmp = &re[l][lowSubband];
        do {
          FIXP_DBL tmp = *(reTmp++);
          maxVal |= (FIXP_DBL)((LONG)(tmp) ^ ((LONG)tmp >> (32 - 1)));
        } while (--k != 0);
      }
    }
  }
  return (maxVal);
}

static void calcNrgPerSubband(FIXP_DBL **analysBufferReal,
                              FIXP_DBL **analysBufferImag, int lowSubband,
                              int highSubband, int start_pos, int next_pos,
                              SCHAR frameExp, FIXP_DBL *nrgEst,
                              SCHAR *nrgEst_e) {
  FIXP_SGL invWidth;
  SCHAR preShift;
  SCHAR shift;
  FIXP_DBL sum;
  int k, l;
  invWidth = static_cast<int16_t>((GetInvInt(next_pos - start_pos)) >> 16);
  frameExp = frameExp << 1;
  for (k = lowSubband; k < highSubband; k++) {
    FIXP_DBL bufferReal[(((1024) / (32)) + (6))];
    FIXP_DBL bufferImag[(((1024) / (32)) + (6))];
    FIXP_DBL maxVal = fixed_runtime_dbl(0.0f);
    if (analysBufferImag != nullptr) {
      for (l = start_pos; l < next_pos; l++) {
        bufferImag[l] = analysBufferImag[l][k];
        maxVal |= (FIXP_DBL)((LONG)(bufferImag[l]) ^
                             ((LONG)bufferImag[l] >> (32 - 1)));
        bufferReal[l] = analysBufferReal[l][k];
        maxVal |= (FIXP_DBL)((LONG)(bufferReal[l]) ^
                             ((LONG)bufferReal[l] >> (32 - 1)));
      }
    }
    else {
      for (l = start_pos; l < next_pos; l++) {
        bufferReal[l] = analysBufferReal[l][k];
        maxVal |= (FIXP_DBL)((LONG)(bufferReal[l]) ^
                             ((LONG)bufferReal[l] >> (32 - 1)));
      }
    }
    if (maxVal != fixed_dbl(0.f)) {
      FIXP_DBL accu = fixed_dbl(0.0f);
      preShift = CntLeadingZeros(maxVal) - 1;
      preShift -= (3);
      if (preShift >= 0) {
        if (analysBufferImag != nullptr) {
          for (l = start_pos; l < next_pos; l++) {
            FIXP_DBL temp1 = bufferReal[l] << (int)preShift;
            FIXP_DBL temp2 = bufferImag[l] << (int)preShift;
            accu = fPow2AddDiv2(accu, temp1);
            accu = fPow2AddDiv2(accu, temp2);
          }
        }
        else {
          for (l = start_pos; l < next_pos; l++) {
            FIXP_DBL temp = bufferReal[l] << (int)preShift;
            accu = fPow2AddDiv2(accu, temp);
          }
        }
      }
      else {
        int negpreShift = -preShift;
        if (analysBufferImag != nullptr) {
          for (l = start_pos; l < next_pos; l++) {
            FIXP_DBL temp1 = bufferReal[l] >> (int)negpreShift;
            FIXP_DBL temp2 = bufferImag[l] >> (int)negpreShift;
            accu = fPow2AddDiv2(accu, temp1);
            accu = fPow2AddDiv2(accu, temp2);
          }
        }
        else {
          for (l = start_pos; l < next_pos; l++) {
            FIXP_DBL temp = bufferReal[l] >> (int)negpreShift;
            accu = fPow2AddDiv2(accu, temp);
          }
        }
      }
      accu <<= 1;
      shift = fNorm(accu);
      sum = accu << (int)shift;
      *nrgEst++ = fMult(sum, invWidth);
      shift += 2 * preShift;
      if (analysBufferImag != nullptr) {
        *nrgEst_e++ = frameExp - shift;
      }
      else {
        *nrgEst_e++ = frameExp - shift + 1;
      }
    }
    else {
      *nrgEst++ = fixed_dbl(0.0f);
      *nrgEst_e++ = 0;
    }
  }
}

static void calcNrgPerSfb(FIXP_DBL **analysBufferReal,
                          FIXP_DBL **analysBufferImag, int nSfb,
                          UCHAR *freqBandTable, int start_pos, int next_pos,
                          SCHAR input_e, FIXP_DBL *nrgEst, SCHAR *nrgEst_e) {
  FIXP_SGL invWidth;
  FIXP_DBL temp;
  SCHAR preShift;
  SCHAR shift, sum_e;
  FIXP_DBL sum;
  int j, k, l, li, ui;
  FIXP_DBL sumAll, sumLine;
  invWidth = static_cast<int16_t>((GetInvInt(next_pos - start_pos)) >> 16);
  input_e = input_e << 1;
  for (j = 0; j < nSfb; j++) {
    li = freqBandTable[j];
    ui = freqBandTable[j + 1];
    FIXP_DBL maxVal = maxSubbandSample(analysBufferReal, analysBufferImag, li,
                                       ui, start_pos, next_pos);
    if (maxVal != fixed_dbl(0.f)) {
      preShift = CntLeadingZeros(maxVal) - 1;
      preShift -= (3);
      sumAll = fixed_dbl(0.0f);
      for (k = li; k < ui; k++) {
        sumLine = fixed_dbl(0.0f);
        if (analysBufferImag != nullptr) {
          if (preShift >= 0) {
            for (l = start_pos; l < next_pos; l++) {
              temp = analysBufferReal[l][k] << (int)preShift;
              sumLine += fPow2Div2(temp);
              temp = analysBufferImag[l][k] << (int)preShift;
              sumLine += fPow2Div2(temp);
            }
          }
          else {
            for (l = start_pos; l < next_pos; l++) {
              temp = analysBufferReal[l][k] >> -(int)preShift;
              sumLine += fPow2Div2(temp);
              temp = analysBufferImag[l][k] >> -(int)preShift;
              sumLine += fPow2Div2(temp);
            }
          }
        }
        else {
          if (preShift >= 0) {
            for (l = start_pos; l < next_pos; l++) {
              temp = analysBufferReal[l][k] << (int)preShift;
              sumLine += fPow2Div2(temp);
            }
          }
          else {
            for (l = start_pos; l < next_pos; l++) {
              temp = analysBufferReal[l][k] >> -(int)preShift;
              sumLine += fPow2Div2(temp);
            }
          }
        }
        sumLine = sumLine >> (4 - 1);
        sumAll += sumLine;
      }
      shift = fNorm(sumAll);
      sum = sumAll << (int)shift;
      sum = fMult(sum, invWidth);
      sum = fMult(sum, static_cast<int16_t>((GetInvInt(ui - li)) >> 16));
      if (analysBufferImag != nullptr) {
        sum_e = input_e + 4 - shift;
      }
      else {
        sum_e = input_e + 4 + 1 - shift;
      }
      sum_e -= 2 * preShift;
    }
    else {
      sum = fixed_dbl(0.0f);
      sum_e = 0;
    }
    for (k = li; k < ui; k++) {
      *nrgEst++ = sum;
      *nrgEst_e++ = sum_e;
    }
  }
}

static void calcSubbandGain(FIXP_DBL nrgRef, SCHAR nrgRef_e,
                            ENV_CALC_NRGS *nrgs, int i, FIXP_DBL tmpNoise,
                            SCHAR tmpNoise_e, UCHAR sinePresentFlag,
                            UCHAR sineMapped, int noNoiseFlag) {
  FIXP_DBL nrgEst = nrgs->nrgEst[i];
  SCHAR nrgEst_e = nrgs->nrgEst_e[i];
  FIXP_DBL *ptrNrgGain = &nrgs->nrgGain[i];
  SCHAR *ptrNrgGain_e = &nrgs->nrgGain_e[i];
  FIXP_DBL *ptrNoiseLevel = &nrgs->noiseLevel[i];
  SCHAR *ptrNoiseLevel_e = &nrgs->noiseLevel_e[i];
  FIXP_DBL *ptrNrgSine = &nrgs->nrgSine[i];
  SCHAR *ptrNrgSine_e = &nrgs->nrgSine_e[i];
  FIXP_DBL a, b, c;
  SCHAR a_e, b_e, c_e;
  b_e = (int)(nrgEst_e - 1);
  if (b_e >= 0) {
    nrgEst = (fixed_dbl(0.5f) >> (INT)fixMin(b_e + 1, 32 - 1)) + (nrgEst >> 1);
    nrgEst_e += 1;
  }
  else {
    nrgEst =
        (nrgEst >> (INT)(fixMin(-b_e + 1, 32 - 1))) + (fixed_dbl(0.5f) >> 1);
    nrgEst_e = 2;
  }
  a = fMult(nrgRef, tmpNoise);
  a_e = nrgRef_e + tmpNoise_e;
  b_e = (int)(tmpNoise_e - 1);
  if (b_e >= 0) {
    b = (fixed_dbl(0.5f) >> (INT)fixMin(b_e + 1, 32 - 1)) + (tmpNoise >> 1);
    b_e = tmpNoise_e + 1;
  }
  else {
    b = (tmpNoise >> (INT)(fixMin(-b_e + 1, 32 - 1))) + (fixed_dbl(0.5f) >> 1);
    b_e = 2;
  }
  FDK_divide_MantExp(a, a_e, b, b_e, ptrNoiseLevel, ptrNoiseLevel_e);
  if (sinePresentFlag) {
    c = fMult(b, nrgEst);
    c_e = b_e + nrgEst_e;
    FDK_divide_MantExp(a, a_e, c, c_e, ptrNrgGain, ptrNrgGain_e);
    if (sineMapped) {
      FDK_divide_MantExp(nrgRef, nrgRef_e, b, b_e, ptrNrgSine, ptrNrgSine_e);
    }
  }
  else {
    if (noNoiseFlag) {
      b = nrgEst;
      b_e = nrgEst_e;
    }
    else {
      b = fMult(b, nrgEst);
      b_e = b_e + nrgEst_e;
    }
    FDK_divide_MantExp(nrgRef, nrgRef_e, b, b_e, ptrNrgGain, ptrNrgGain_e);
  }
}

static void calcAvgGain(ENV_CALC_NRGS *nrgs, int lowSubband, int highSubband,
                        FIXP_DBL *ptrSumRef, SCHAR *ptrSumRef_e,
                        FIXP_DBL *ptrAvgGain, SCHAR *ptrAvgGain_e) {
  FIXP_DBL *nrgRef = nrgs->nrgRef;
  SCHAR *nrgRef_e = nrgs->nrgRef_e;
  FIXP_DBL *nrgEst = nrgs->nrgEst;
  SCHAR *nrgEst_e = nrgs->nrgEst_e;
  FIXP_DBL sumRef = 1;
  FIXP_DBL sumEst = 1;
  SCHAR sumRef_e = -16;
  SCHAR sumEst_e = -16;
  int k;
  for (k = lowSubband; k < highSubband; k++) {
    FDK_add_MantExp(sumRef, sumRef_e, nrgRef[k], nrgRef_e[k], &sumRef,
                    &sumRef_e);
    FDK_add_MantExp(sumEst, sumEst_e, nrgEst[k], nrgEst_e[k], &sumEst,
                    &sumEst_e);
  }
  FDK_divide_MantExp(sumRef, sumRef_e, sumEst, sumEst_e, ptrAvgGain,
                     ptrAvgGain_e);
  *ptrSumRef = sumRef;
  *ptrSumRef_e = sumRef_e;
}

static void adjustTimeSlot_EldGrid(FIXP_DBL *ptrReal, ENV_CALC_NRGS *nrgs,
                                   UCHAR *ptrHarmIndex, int lowSubband,
                                   int noSubbands, int scale_change,
                                   int noNoiseFlag, int *ptrPhaseIndex,
                                   int scale_diff_low) {
  int k;
  FIXP_DBL signalReal, sbNoise;
  int tone_count = 0;
  FIXP_DBL *pGain = nrgs->nrgGain;
  FIXP_DBL *pNoiseLevel = nrgs->noiseLevel;
  FIXP_DBL *pSineLevel = nrgs->nrgSine;
  int phaseIndex = *ptrPhaseIndex;
  UCHAR harmIndex = *ptrHarmIndex;
  static const INT harmonicPhase[2][4] = {{1, 0, -1, 0}, {0, 1, 0, -1}};
  static const FIXP_DBL harmonicPhaseX[2][4] = {
      {fixed_dbl(2.0 * 1.245183154539139e-001),
       fixed_dbl(2.0 * -1.123767859325028e-001),
       fixed_dbl(2.0 * -1.245183154539139e-001),
       fixed_dbl(2.0 * 1.123767859325028e-001)},
      {fixed_dbl(2.0 * 1.245183154539139e-001),
       fixed_dbl(2.0 * 1.123767859325028e-001),
       fixed_dbl(2.0 * -1.245183154539139e-001),
       fixed_dbl(2.0 * -1.123767859325028e-001)}};
  for (k = 0; k < noSubbands; k++) {
    phaseIndex = (phaseIndex + 1) & (512 - 1);
    if ((pSineLevel[0] != fixed_dbl(0.0f)) || (noNoiseFlag == 1)) {
      sbNoise = fixed_dbl(0.0f);
    }
    else {
      sbNoise = pNoiseLevel[0];
    }
    signalReal = fMultDiv2(*ptrReal, *pGain) << ((int)scale_change);
    signalReal +=
        (fMultDiv2(FDK_sbrDecoder_sbr_randomPhase[phaseIndex][0], sbNoise)
         << 4);
    signalReal += pSineLevel[0] * harmonicPhase[0][harmIndex];
    *ptrReal = signalReal;
    if (k == 0) {
      *(ptrReal - 1) += scaleValue(
          fMultDiv2(harmonicPhaseX[lowSubband & 1][harmIndex], pSineLevel[0]),
          -scale_diff_low);
      if (k < noSubbands - 1) {
        *(ptrReal) += fMultDiv2(
            pSineLevel[1], harmonicPhaseX[(lowSubband + 1) & 1][harmIndex]);
      }
    }
    if (k > 0 && k < noSubbands - 1 && tone_count < 16) {
      *(ptrReal) += fMultDiv2(pSineLevel[-1],
                              harmonicPhaseX[(lowSubband + k) & 1][harmIndex]);
      *(ptrReal) += fMultDiv2(
          pSineLevel[+1], harmonicPhaseX[(lowSubband + k + 1) & 1][harmIndex]);
    }
    if (k == noSubbands - 1 && tone_count < 16) {
      if (k > 0) {
        *(ptrReal) += fMultDiv2(
            pSineLevel[-1], harmonicPhaseX[(lowSubband + k) & 1][harmIndex]);
      }
      if (k + lowSubband + 1 < 63) {
        *(ptrReal + 1) += fMultDiv2(
            pSineLevel[0], harmonicPhaseX[(lowSubband + k + 1) & 1][harmIndex]);
      }
    }
    if (pSineLevel[0] != fixed_dbl(0.0f)) {
      tone_count++;
    }
    ptrReal++;
    pNoiseLevel++;
    pGain++;
    pSineLevel++;
  }
  *ptrHarmIndex = (harmIndex + 1) & 3;
  *ptrPhaseIndex = phaseIndex & (512 - 1);
}

static void adjustTimeSlotLC(FIXP_DBL *ptrReal, ENV_CALC_NRGS *nrgs,
                             UCHAR *ptrHarmIndex, int lowSubband,
                             int noSubbands, int scale_change, int noNoiseFlag,
                             int *ptrPhaseIndex) {
  FIXP_DBL *pGain = nrgs->nrgGain;
  FIXP_DBL *pNoiseLevel = nrgs->noiseLevel;
  FIXP_DBL *pSineLevel = nrgs->nrgSine;
  int k;
  int index = *ptrPhaseIndex;
  UCHAR harmIndex = *ptrHarmIndex;
  UCHAR freqInvFlag = (lowSubband & 1);
  FIXP_DBL signalReal, sineLevel, sineLevelNext, sineLevelPrev;
  int tone_count = 0;
  int sineSign = 1;
  index = (index + 1) & (512 - 1);
  signalReal = fMultDiv2(*ptrReal, *pGain++) << ((int)scale_change);
  sineLevel = *pSineLevel++;
  sineLevelNext = (noSubbands > 1) ? pSineLevel[0] : fixed_dbl(0.0f);
  if (sineLevel != fixed_dbl(0.0f)) {
    tone_count++;
  }
  else if (!noNoiseFlag) {
    signalReal +=
        (fMultDiv2(FDK_sbrDecoder_sbr_randomPhase[index][0], pNoiseLevel[0])
         << 4);
  }
  {
    if (!(harmIndex & 0x1)) {
      signalReal += (harmIndex & 0x2) ? -sineLevel : sineLevel;
      *ptrReal++ = signalReal;
    }
    else {
      int shift = (int)(scale_change + 1);
      shift = (shift >= 0) ? fixMin(32 - 1, shift) : fixMax(-(32 - 1), shift);
      FIXP_DBL tmp1 =
          (shift >= 0)
              ? (fMultDiv2(((FIXP_SGL)fixed_sgl(2.f * 0.00815f)), sineLevel) >>
                 shift)
              : (fMultDiv2(((FIXP_SGL)fixed_sgl(2.f * 0.00815f)), sineLevel)
                 << (-shift));
      FIXP_DBL tmp2 =
          fMultDiv2(((FIXP_SGL)fixed_sgl(2.f * 0.00815f)), sineLevelNext);
      if (((harmIndex >> 1) & 0x1) ^ freqInvFlag) {
        *(ptrReal - 1) += tmp1;
        signalReal -= tmp2;
      }
      else {
        *(ptrReal - 1) -= tmp1;
        signalReal += tmp2;
      }
      *ptrReal++ = signalReal;
      freqInvFlag = !freqInvFlag;
    }
  }
  pNoiseLevel++;
  if (noSubbands > 2) {
    if (!(harmIndex & 0x1)) {
      if (!harmIndex) {
        sineSign = 0;
      }
      for (k = noSubbands - 2; k != 0; k--) {
        FIXP_DBL sinelevel = *pSineLevel++;
        index++;
        if (((signalReal = (sineSign ? -sinelevel : sinelevel)) ==
             fixed_dbl(0.0f)) &&
            !noNoiseFlag) {
          index &= (512 - 1);
          signalReal += (fMultDiv2(FDK_sbrDecoder_sbr_randomPhase[index][0],
                                   pNoiseLevel[0])
                         << 4);
        }
        signalReal += fMultDiv2(*ptrReal, *pGain++) << ((int)scale_change);
        pNoiseLevel++;
        *ptrReal++ = signalReal;
      }
    }
    else {
      if (harmIndex == 1) {
        freqInvFlag = !freqInvFlag;
      }
      for (k = noSubbands - 2; k != 0; k--) {
        index++;
        signalReal = fMultDiv2(*ptrReal, *pGain++) << ((int)scale_change);
        if (*pSineLevel++ != fixed_dbl(0.0f)) {
          tone_count++;
        }
        else if (!noNoiseFlag) {
          index &= (512 - 1);
          signalReal += (fMultDiv2(FDK_sbrDecoder_sbr_randomPhase[index][0],
                                   pNoiseLevel[0])
                         << 4);
        }
        pNoiseLevel++;
        if (tone_count <= 16) {
          FIXP_DBL addSine = fMultDiv2((pSineLevel[-2] - pSineLevel[0]),
                                       ((FIXP_SGL)fixed_sgl(2.f * 0.00815f)));
          signalReal += (freqInvFlag) ? (-addSine) : (addSine);
        }
        *ptrReal++ = signalReal;
        freqInvFlag = !freqInvFlag;
      }
    }
  }
  if (noSubbands > -1) {
    index++;
    signalReal = fMultDiv2(*ptrReal, *pGain) << ((int)scale_change);
    sineLevelPrev = fMultDiv2(pSineLevel[-1], fixed_runtime_sgl(0.0163f));
    sineLevel = pSineLevel[0];
    if (pSineLevel[0] != fixed_dbl(0.0f)) {
      tone_count++;
    }
    else if (!noNoiseFlag) {
      index &= (512 - 1);
      signalReal =
          signalReal +
          (fMultDiv2(FDK_sbrDecoder_sbr_randomPhase[index][0], pNoiseLevel[0])
           << 4);
    }
    if (!(harmIndex & 0x1)) {
      *ptrReal = signalReal + ((sineSign) ? -sineLevel : sineLevel);
    }
    else {
      if (tone_count <= 16) {
        if (freqInvFlag) {
          *ptrReal++ = signalReal - sineLevelPrev;
          if (noSubbands + lowSubband < 63) {
            *ptrReal =
                *ptrReal +
                fMultDiv2(((FIXP_SGL)fixed_sgl(2.f * 0.00815f)), sineLevel);
          }
        }
        else {
          *ptrReal++ = signalReal + sineLevelPrev;
          if (noSubbands + lowSubband < 63) {
            *ptrReal =
                *ptrReal -
                fMultDiv2(((FIXP_SGL)fixed_sgl(2.f * 0.00815f)), sineLevel);
          }
        }
      }
      else {
        *ptrReal = signalReal;
      }
    }
  }
  *ptrHarmIndex = (harmIndex + 1) & 3;
  *ptrPhaseIndex = index & (512 - 1);
}

static void adjustTimeSlotHQ(FIXP_DBL *ptrReal, FIXP_DBL *ptrImag,
                             HANDLE_SBR_CALCULATE_ENVELOPE h_sbr_cal_env,
                             ENV_CALC_NRGS *nrgs, int lowSubband,
                             int noSubbands, int scale_change,
                             FIXP_SGL smooth_ratio, int noNoiseFlag,
                             int filtBufferNoiseShift) {
  FIXP_DBL *gain = nrgs->nrgGain;
  FIXP_DBL *noiseLevel = nrgs->noiseLevel;
  FIXP_DBL *pSineLevel = nrgs->nrgSine;
  FIXP_DBL *filtBuffer = h_sbr_cal_env->filtBuffer;
  FIXP_DBL *filtBufferNoise = h_sbr_cal_env->filtBufferNoise;
  UCHAR *ptrHarmIndex = &h_sbr_cal_env->harmIndex;
  int *ptrPhaseIndex = &h_sbr_cal_env->phaseIndex;
  int k;
  FIXP_DBL signalReal, signalImag;
  FIXP_DBL noiseReal, noiseImag;
  FIXP_DBL smoothedGain, smoothedNoise;
  FIXP_SGL direct_ratio = (FIXP_SGL)32767 - smooth_ratio;
  int index = *ptrPhaseIndex;
  UCHAR harmIndex = *ptrHarmIndex;
  int freqInvFlag = (lowSubband & 1);
  FIXP_DBL sineLevel;
  int shift;
  *ptrPhaseIndex = (index + noSubbands) & (512 - 1);
  *ptrHarmIndex = (harmIndex + 1) & 3;
  filtBufferNoiseShift += 1;
  if (filtBufferNoiseShift < 0) {
    shift = fixMin(32 - 1, -filtBufferNoiseShift);
  }
  else {
    shift = fixMin(32 - 1, filtBufferNoiseShift);
  }
  if (smooth_ratio > fixed_sgl(0.0f)) {
    for (k = 0; k < noSubbands; k++) {
      smoothedGain =
          fMult(smooth_ratio, filtBuffer[k]) + fMult(direct_ratio, gain[k]);
      if (filtBufferNoiseShift < 0) {
        smoothedNoise = (fMultDiv2(smooth_ratio, filtBufferNoise[k]) >> shift) +
                        fMult(direct_ratio, noiseLevel[k]);
      }
      else {
        smoothedNoise = (fMultDiv2(smooth_ratio, filtBufferNoise[k]) << shift) +
                        fMult(direct_ratio, noiseLevel[k]);
      }
      signalReal = fMultDiv2(*ptrReal, smoothedGain) << ((int)scale_change);
      signalImag = fMultDiv2(*ptrImag, smoothedGain) << ((int)scale_change);
      index++;
      if (pSineLevel[k] != fixed_dbl(0.0f)) {
        sineLevel = pSineLevel[k];
        switch (harmIndex) {
          case 0:
            *ptrReal++ = (signalReal + sineLevel);
            *ptrImag++ = (signalImag);
            break;
          case 2:
            *ptrReal++ = (signalReal - sineLevel);
            *ptrImag++ = (signalImag);
            break;
          case 1:
            *ptrReal++ = (signalReal);
            if (freqInvFlag) {
              *ptrImag++ = (signalImag - sineLevel);
            }
            else {
              *ptrImag++ = (signalImag + sineLevel);
            }
            break;
          case 3:
            *ptrReal++ = signalReal;
            if (freqInvFlag) {
              *ptrImag++ = (signalImag + sineLevel);
            }
            else {
              *ptrImag++ = (signalImag - sineLevel);
            }
            break;
        }
      }
      else {
        if (noNoiseFlag) {
          *ptrReal++ = (signalReal);
          *ptrImag++ = (signalImag);
        }
        else {
          index &= (512 - 1);
          noiseReal =
              fMultDiv2(FDK_sbrDecoder_sbr_randomPhase[index][0], smoothedNoise)
              << 4;
          noiseImag =
              fMultDiv2(FDK_sbrDecoder_sbr_randomPhase[index][1], smoothedNoise)
              << 4;
          *ptrReal++ = (signalReal + noiseReal);
          *ptrImag++ = (signalImag + noiseImag);
        }
      }
      freqInvFlag ^= 1;
    }
  }
  else {
    for (k = 0; k < noSubbands; k++) {
      smoothedGain = gain[k];
      signalReal = fMultDiv2(*ptrReal, smoothedGain) << scale_change;
      signalImag = fMultDiv2(*ptrImag, smoothedGain) << scale_change;
      index++;
      if ((sineLevel = pSineLevel[k]) != fixed_dbl(0.0f)) {
        switch (harmIndex) {
          case 0:
            signalReal += sineLevel;
            break;
          case 1:
            if (freqInvFlag) {
              signalImag -= sineLevel;
            }
            else {
              signalImag += sineLevel;
            }
            break;
          case 2:
            signalReal -= sineLevel;
            break;
          case 3:
            if (freqInvFlag) {
              signalImag += sineLevel;
            }
            else {
              signalImag -= sineLevel;
            }
            break;
        }
      }
      else {
        if (noNoiseFlag == 0) {
          smoothedNoise = noiseLevel[k];
          index &= (512 - 1);
          noiseReal = fMultDiv2(FDK_sbrDecoder_sbr_randomPhase[index][0],
                                smoothedNoise);
          noiseImag = fMultDiv2(FDK_sbrDecoder_sbr_randomPhase[index][1],
                                smoothedNoise);
          signalReal += noiseReal << 4;
          signalImag += noiseImag << 4;
        }
      }
      *ptrReal++ = signalReal;
      *ptrImag++ = signalImag;
      freqInvFlag ^= 1;
    }
  }
}

