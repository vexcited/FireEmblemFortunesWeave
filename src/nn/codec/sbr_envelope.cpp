inline FIXP_DBL sqrtFixp_lookup(FIXP_DBL x, INT *x_e) {
  UINT y = (INT)x;
  INT e;
  if (x == (FIXP_DBL)0) {
    return x;
  }
  e = fixnormz_D(y);
  y <<= e;
  e = *x_e - e + 2;
  if (e & 1) {
    y >>= 1;
    e++;
  }
  UINT idx = (y >> 26) - 16;
  USHORT frac = (y >> 10) & 0xffff;
  USHORT nfrac = 0xffff ^ frac;
  UINT t = nfrac * sqrt_tab[idx] + frac * sqrt_tab[idx + 1];
  *x_e = e >> 1;
  return (FIXP_DBL)(LONG)(t >> 1);
}

static FIXP_DBL GetInvInt(int value) {
  return invCount[value];
}

inline void FDK_add_MantExp(FIXP_DBL a, SCHAR a_e, FIXP_DBL b, SCHAR b_e,
                            FIXP_DBL *ptrSum, SCHAR *ptrSum_e) {
  FIXP_DBL accu;
  int shift;
  int shiftAbs;
  FIXP_DBL shiftedMantissa;
  FIXP_DBL otherMantissa;
  shift = (int)(a_e - b_e);
  shiftAbs = (shift > 0) ? shift : -shift;
  shiftAbs = (shiftAbs < 32 - 1) ? shiftAbs : 32 - 1;
  shiftedMantissa = (shift > 0) ? (b >> shiftAbs) : (a >> shiftAbs);
  otherMantissa = (shift > 0) ? a : b;
  *ptrSum_e = (shift > 0) ? a_e : b_e;
  accu = (shiftedMantissa >> 1) + (otherMantissa >> 1);
  if ((accu >= (fixed_dbl(0.5f) - (FIXP_DBL)1)) || (accu <= fixed_dbl(-0.5f))) {
    *ptrSum_e += 1;
  }
  else {
    accu = (shiftedMantissa + otherMantissa);
  }
  *ptrSum = accu;
}

static inline void FDK_divide_MantExp(FIXP_DBL a_m, SCHAR a_e, FIXP_DBL b_m,
                                      SCHAR b_e, FIXP_DBL *ptrResult_m,
                                      SCHAR *ptrResult_e) {
  int preShift, postShift, index, shift;
  FIXP_DBL ratio_m;
  FIXP_SGL bInv_m = fixed_sgl(0.0f);
  preShift = CntLeadingZeros(b_m);
  shift = (32 - 2 - 8 - preShift);
  index = (shift < 0) ? (LONG)b_m << (-shift) : (LONG)b_m >> shift;
  index &= (1 << (8 + 1)) - 1;
  index--;
  index = index >> 1;
  bInv_m = (index < 0) ? bInv_m : FDK_sbrDecoder_invTable[index];
  ratio_m = (index < 0) ? (a_m >> 1) : fMultDiv2(bInv_m, a_m);
  postShift = CntLeadingZeros(ratio_m) - 1;
  *ptrResult_m = ratio_m << postShift;
  *ptrResult_e = a_e - b_e + 1 + preShift - postShift;
}

static inline void FDK_sqrt_MantExp(FIXP_DBL *mantissa, SCHAR *exponent,
                                    const SCHAR *destScale) {
  FIXP_DBL input_m = *mantissa;
  int input_e = (int)*exponent;
  FIXP_DBL result = fixed_dbl(0.0f);
  int result_e = -16;
  result = sqrtFixp_lookup(input_m, &input_e);
  result_e = input_e;
  if (exponent == destScale) {
    *mantissa = result;
    *exponent = result_e;
  }
  else {
    int shift = result_e - *destScale;
    *mantissa = (shift >= 0) ? result << (INT)fixMin(32 - 1, shift)
                             : result >> (INT)fixMin(32 - 1, -shift);
    *exponent = *destScale;
  }
}

static FIXP_DBL schur_div(FIXP_DBL num, FIXP_DBL denum, INT count) {
  INT L_num = (LONG)num >> 1;
  INT L_denum = (LONG)denum >> 1;
  INT div = 0;
  INT k = count;
  if (L_num != 0) {
    while (--k) {
      div <<= 1;
      L_num <<= 1;
      if (L_num >= L_denum) {
        L_num -= L_denum;
        div++;
      }
    }
  }
  return (FIXP_DBL)(div << (32 - count));
}

FIXP_DBL fDivNorm(FIXP_DBL L_num, FIXP_DBL L_denum, INT *result_e) {
  FIXP_DBL div;
  INT norm_num, norm_den;
  if (L_num == (FIXP_DBL)0) {
    *result_e = 0;
    return ((FIXP_DBL)0);
  }
  norm_num = CountLeadingBits(L_num);
  L_num = L_num << norm_num;
  L_num = L_num >> 1;
  *result_e = -norm_num + 1;
  norm_den = CountLeadingBits(L_denum);
  L_denum = L_denum << norm_den;
  *result_e -= -norm_den;
  div = schur_div(L_num, L_denum, 16);
  return div;
}

